let current = 'ru';
function detectLang(systemLang) {
  return /^ru/i.test(systemLang || '') ? 'ru' : 'en';
}
function setLang(lang) {
  current = DICT[lang] ? lang : 'ru';
}
function t(key, params) {
  let s = (DICT[current] && DICT[current][key]) || DICT.ru[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, v);
    }
  }
  return s;
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { DICT, t, setLang, detectLang, getLang: () => current };
}

